_meshopt_lib = None


def _meshopt_library_names():
    """Return the shared-library names generated by CMake for this platform."""
    if sys.platform.startswith(("win", "cygwin", "msys")):
        # MSVC uses meshoptimizer.dll; MinGW may add the conventional lib
        # prefix, so accept both names without falling back to the old DLL.
        return ("meshoptimizer.dll", "libmeshoptimizer.dll")
    if sys.platform == "darwin":
        return ("libmeshoptimizer.dylib",)
    if sys.platform.startswith((
        "linux", "freebsd", "openbsd", "netbsd", "dragonfly", "sunos", "aix"
    )):
        return ("libmeshoptimizer.so",)
    return ()


def _meshopt_library_candidates():
    """Return local build outputs followed by an optional system library."""
    script_dir = os.path.dirname(os.path.abspath(__file__))
    local_dir = os.path.join(script_dir, "_meshopt", "lib")
    candidates = [
        os.path.join(local_dir, name)
        for name in _meshopt_library_names()
    ]

    # This keeps the checkout-local CMake build as the preferred ABI while
    # still allowing a system installation to be used by advanced users.
    found = ctypes.util.find_library("meshoptimizer")
    if found and found not in candidates:
        candidates.append(found)
    return candidates


def _configure_meshopt_library(lib):
    """Declare the meshoptimizer C API used by the decoder."""
    # meshoptimizer uses size_t for all count/size parameters.  c_size_t is
    # portable across 32-bit and 64-bit Python builds.
    lib.meshopt_decodeVertexBuffer.restype = ctypes.c_int
    lib.meshopt_decodeVertexBuffer.argtypes = [
        ctypes.c_void_p, ctypes.c_size_t, ctypes.c_size_t,
        ctypes.POINTER(ctypes.c_uint8), ctypes.c_size_t
    ]
    lib.meshopt_decodeIndexBuffer.restype = ctypes.c_int
    lib.meshopt_decodeIndexBuffer.argtypes = [
        ctypes.c_void_p, ctypes.c_size_t, ctypes.c_size_t,
        ctypes.POINTER(ctypes.c_uint8), ctypes.c_size_t
    ]
    return lib


def _load_meshopt_lib():
    global _meshopt_lib
    if _meshopt_lib is not None:
        return _meshopt_lib

    candidates = _meshopt_library_candidates()
    for name in candidates:
        try:
            _meshopt_lib = _configure_meshopt_library(ctypes.CDLL(name))
            print(f"  [meshopt] 已加载动态库: {name}")
            return _meshopt_lib
        except (AttributeError, OSError):
            continue

    platform_name = sys.platform or "unknown"
    if candidates:
        tried = ", ".join(candidates)
        print(f"  [meshopt] 未找到适用于 {platform_name} 的动态库（已尝试: {tried}）")
    else:
        print(f"  [meshopt] 暂不支持平台 {platform_name} 的动态库加载")
    _meshopt_lib = False
    return None


